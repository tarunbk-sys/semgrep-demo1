import { Config, matchesAny } from "./config.js";
import { ChangedFile, Range, changedRanges, fileAt } from "./git.js";
import { redactLine } from "./redact.js";

export interface SecretHit {
  file: string;
  line: number;
  type: string;
}

export interface FileContext {
  path: string;
  changedLines: Set<number>;
  changedCount: number;
  text: string; // rendered, line-numbered, redacted
  tokens: number;
  risk: number;
  secrets: SecretHit[];
}

const CTX = 25; // lines of context around each hunk
const DECL =
  /^\s*(export\s+)?(default\s+)?(async\s+)?(function\*?|class|interface|def|func|fn|impl|struct|enum|trait|module|public|private|protected|static|abstract)\b|^\s*(export\s+)?(const|let|var)\s+\w+\s*(:[^=]+)?=\s*(async\s*)?(\([^)]*\)|\w+)\s*(:[^=]+)?=>/;
const IMPORT = /^\s*(import|from|require|using|use|package|#include|extern crate)\b|=\s*require\(/;

export const estimateTokens = (s: string) => Math.ceil(s.length / 4);

export function shouldSkip(f: ChangedFile, cfg: Config, head: string): string | null {
  if (f.binary) return "binary";
  if (matchesAny(f.path, cfg.ignore)) return "ignored (lockfile/vendored/generated/asset)";
  return null;
}

function looksGenerated(lines: string[]): boolean {
  return lines.slice(0, 5).some((l) => /do not edit|generated by|@generated|auto-generated/i.test(l));
}

export function buildContext(r: Range, f: ChangedFile, cfg: Config): FileContext | { skipped: string } {
  const raw = fileAt(r.head, f.path);
  if (raw === null) return { skipped: "unreadable" };
  // content-based binary check (git's own heuristic misses short/odd files)
  const bad = (raw.match(/[\0�]/g) ?? []).length;
  if (bad > 0 && bad / Math.max(raw.length, 1) > 0.02) return { skipped: "binary" };
  const lines = raw.split("\n");
  if (looksGenerated(lines)) return { skipped: "generated header" };

  const ranges = changedRanges(r, f.path);
  if (!ranges.length) return { skipped: "no textual changes" };

  // redact every line up front; remember which hits are on changed lines
  const secrets: SecretHit[] = [];
  const safe = lines.map((l) => redactLine(l));
  const changed = new Set<number>();
  for (const { start, end } of ranges) for (let n = start; n <= end && n <= lines.length; n++) changed.add(n);
  for (const n of changed) for (const type of safe[n - 1]?.hits ?? []) secrets.push({ file: f.path, line: n, type });

  const keep: [number, number][] = [];
  for (const { start, end } of ranges) {
    let from = Math.max(1, start - CTX);
    // pull in the enclosing function/class declaration (scan upward, bounded)
    for (let n = start; n >= Math.max(1, start - 150); n--) {
      if (DECL.test(lines[n - 1] ?? "")) {
        from = Math.min(from, n);
        break;
      }
    }
    keep.push([from, Math.min(lines.length, end + CTX)]);
  }

  // imports header (first 120 lines)
  const imports: number[] = [];
  for (let n = 1; n <= Math.min(120, lines.length); n++) if (IMPORT.test(lines[n - 1])) imports.push(n);
  for (const n of imports) keep.push([n, n]);

  // type definitions referenced by changed lines (same file only)
  const ids = new Set<string>();
  for (const n of changed) for (const m of (lines[n - 1] ?? "").matchAll(/\b[A-Z][A-Za-z0-9_]{2,}\b/g)) ids.add(m[0]);
  let typeCount = 0;
  for (const id of ids) {
    if (typeCount >= 5) break;
    const re = new RegExp(`\\b(interface|type|class|enum|struct|record)\\s+${id}\\b`);
    const idx = lines.findIndex((l) => re.test(l));
    if (idx >= 0) {
      let end = idx;
      while (end < Math.min(lines.length - 1, idx + 30) && !/^[}\]]/.test(lines[end + 1] ?? "")) end++;
      keep.push([idx + 1, Math.min(lines.length, end + 2)]);
      typeCount++;
    }
  }

  // merge ranges
  keep.sort((a, b) => a[0] - b[0]);
  const merged: [number, number][] = [];
  for (const k of keep) {
    const last = merged[merged.length - 1];
    if (last && k[0] <= last[1] + 3) last[1] = Math.max(last[1], k[1]);
    else merged.push([...k]);
  }

  const out: string[] = [`=== FILE: ${f.path} (${f.status === "A" ? "new file" : "modified"}) ===`];
  let prevEnd = 0;
  for (const [a, b] of merged) {
    if (a > prevEnd + 1) out.push("   ...");
    for (let n = a; n <= b; n++) out.push(`${String(n).padStart(5)} ${changed.has(n) ? "+" : " "} ${safe[n - 1].text}`);
    prevEnd = b;
  }
  if (prevEnd < lines.length) out.push("   ...");
  const text = out.join("\n");

  const risk = (matchesAny(f.path, cfg.highRisk) ? 100 : 0) + Math.min(changed.size, 99);
  return {
    path: f.path,
    changedLines: changed,
    changedCount: changed.size,
    text,
    tokens: estimateTokens(text),
    risk,
    secrets,
  };
}

export interface Budgeted {
  selected: FileContext[];
  dropped: { path: string; reason: string }[];
}

/** Caps cost: highest-risk files first until a file/line/token budget is exhausted. */
export function applyBudget(ctxs: FileContext[], cfg: Config): Budgeted {
  const sorted = [...ctxs].sort((a, b) => b.risk - a.risk);
  const selected: FileContext[] = [];
  const dropped: { path: string; reason: string }[] = [];
  let lines = 0;
  let tokens = 0;
  for (const c of sorted) {
    if (selected.length >= cfg.maxFiles) dropped.push({ path: c.path, reason: "file cap" });
    else if (lines + c.changedCount > cfg.maxChangedLines) dropped.push({ path: c.path, reason: "changed-line cap" });
    else if (tokens + c.tokens > cfg.maxInputTokens) dropped.push({ path: c.path, reason: "token cap" });
    else {
      selected.push(c);
      lines += c.changedCount;
      tokens += c.tokens;
    }
  }
  return { selected, dropped };
}
